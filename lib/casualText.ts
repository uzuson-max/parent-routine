// lib/casualText.ts
// ============================================================================
// 참견이 말투 — 문장 끝에 마침표를 찍지 않는다.
// ----------------------------------------------------------------------------
// 써본 사람들 피드백: "문장마다 점이 찍혀 있어서 아줌마가 만든 앱 같다".
// 친구끼리 카톡하듯 마침표 없이 말한다. 물음표·느낌표·말줄임표(…, ...)·ㅋㅋ는 그대로 둔다.
//   - 문장 사이 마침표 → 줄바꿈 (줄바꿈을 안 보여주는 곳에선 띄어쓰기처럼 보인다)
//   - 맨 끝 마침표 → 지움
// AI가 만든 대답(화면 말풍선·편지·문자)에 쓴다. 고정 문구는 처음부터 마침표 없이 쓴다.
// 전화(음성 읽기)에는 쓰지 않는다 — 마침표가 있어야 읽을 때 쉬는 자리가 생긴다.
// ============================================================================

// 마침표 앞 글자: 한글/자모/숫자 아닌 것 중 문장 끝에 올 만한 것들
const END = "[가-힣ㄱ-ㅎㅏ-ㅣa-zA-Z)~\\]\"'”’]";

export function casual(text: string | null | undefined): string {
  if (!text) return "";
  let t = String(text).trim();
  // 문장 사이: "…했어. 근데" → "…했어\n근데"  (… / ... / 1.5 같은 숫자는 건드리지 않음)
  t = t.replace(new RegExp(`(${END})\\.(?!\\.)[ \\t]+(?=\\S)`, "g"), "$1\n");
  // 줄 끝: "…했어.\n" → "…했어\n"
  t = t.replace(new RegExp(`(${END})\\.(?!\\.)(?=\\n)`, "g"), "$1");
  // 맨 끝
  t = t.replace(new RegExp(`(${END})\\.(?!\\.)\\s*$`), "$1");
  return t;
}
